import { createReadStream, existsSync, statSync } from "node:fs";
import { createServer } from "node:http";
import { extname, join, normalize, resolve } from "node:path";
import { chromium } from "@playwright/test";
const root = resolve("dist");
const server = createServer((req, res) => {
  let f = normalize(join(root, decodeURIComponent(req.url.split("?")[0])));
  if (!existsSync(f) || statSync(f).isDirectory()) f = join(root, "index.html");
  const t = { ".js": "text/javascript", ".css": "text/css", ".html": "text/html" }[extname(f)];
  res.writeHead(200, t ? { "content-type": t } : {});
  createReadStream(f).pipe(res);
});
await new Promise((ok) => server.listen(0, "127.0.0.1", ok));
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "no-preference" });
await ctx.addInitScript(`localStorage.setItem("tw.reduceMotion","off")`);
const page = await ctx.newPage();
await page.goto(`http://127.0.0.1:${server.address().port}/`, { waitUntil: "load" });
await page.waitForTimeout(2500);
await page.getByRole("radio", { name: "Local app" }).check();
await page.getByLabel("Local app URL", { exact: false }).fill("http://localhost:4321");
await page.getByRole("radio", { name: /^Open hunt/ }).check();
